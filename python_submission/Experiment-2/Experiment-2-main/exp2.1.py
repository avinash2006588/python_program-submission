m=float(input("enter your percentage="))
if m>=90 and m<=100:
    print("O grade")
if m>=80 and m<90:
    print("E grade")
elif m>=70 and m<80:
    print("A grade")
elif m>=60 and m<70:
    print("B grade")
elif m>=50 and m<60:
    print("C grade")
elif m>=40 and m<50:
    print("D grade")
else:
    print("F grade")
